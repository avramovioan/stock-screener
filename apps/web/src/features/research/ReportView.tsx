import { Info } from "lucide-react";
import { MarkdownBody } from "./MarkdownBody";
import type { ClaimGroup, ReportData } from "./types";

const SECTION_TITLE: Record<ClaimGroup["section"], string> = {
  established_facts: "Established facts",
  management_claims: "Management claims",
  forecasts: "Forecasts",
  allegations: "Allegations",
  interpretation: "Interpretation",
};
const yesNo = (v: boolean | null) => (v === null ? "unknown" : v ? "yes" : "no");

export function ReportView({ data }: { data: ReportData }) {
  return (
    <article className="mx-auto max-w-4xl space-y-6 px-4 py-6">
      <header className="space-y-1">
        <h1 id="page-title" className="text-2xl font-semibold">
          {data.companyName} <span className="text-muted-foreground">{data.ticker}</span>
        </h1>
        <p className="text-sm">{`Research date: ${data.researchDate}`}</p>
        <p className="text-sm">{`Cutoff date: ${data.cutoffDate ?? "not stated"}`}</p>
        <p className="text-xs text-muted-foreground">
          {`Generated by ${data.provider ?? "unknown"} / ${data.model ?? "unknown"}, prompt ${data.promptVersion ?? "?"}, schema ${data.schemaVersion ?? "?"}`}
        </p>
      </header>

      <aside
        role="note"
        className="flex gap-3 rounded-lg border border-l-4 border-l-foreground bg-muted p-4 text-sm"
      >
        <Info aria-hidden="true" size={18} className="mt-0.5 shrink-0" />
        <p>
          This research was generated by an AI model from the listed public sources. It is not
          financial advice, it may be wrong, and the model and provider are shown above. Check the
          sources before acting.
        </p>
      </aside>

      <p className="text-xs text-muted-foreground">
        The conclusion and the bankruptcy risk are two separate outputs and can differ.
      </p>
      <div className="grid gap-4 md:grid-cols-2">
        <section aria-label="Research conclusion" className="rounded-lg border bg-card p-4">
          <h2 className="text-sm font-medium text-muted-foreground">Research conclusion</h2>
          <p className="mt-1 font-medium">{data.conclusion ?? "No conclusion"}</p>
        </section>
        <section aria-label="Bankruptcy risk" className="rounded-lg border bg-card p-4">
          <h2 className="text-sm font-medium text-muted-foreground">Bankruptcy risk</h2>
          <p className="mt-1 font-medium">{data.bankruptcyRisk ?? "Unclear"}</p>
          <p className="text-sm">{`Sufficient evidence: ${yesNo(data.sufficientEvidence)}`}</p>
          <p className="text-sm">{`Material lasting damage established: ${yesNo(data.materialDamageEstablished)}`}</p>
        </section>
      </div>

      <MarkdownBody markdown={data.reportMd} allowedUrls={data.sourceUrls ?? []} />

      {data.claims
        .filter((g) => g.items.length > 0)
        .map((group) => (
          <section key={group.section} className="space-y-1">
            <h2 className="text-base font-medium">{SECTION_TITLE[group.section]}</h2>
            <ul className="list-disc pl-5 text-sm">
              {group.items.map((item, idx) => (
                // biome-ignore lint/suspicious/noArrayIndexKey: static list; identical claim texts must not collide
                <li key={`${idx}-${item.text}`}>
                  <span>{item.text}</span>{" "}
                  <span className="text-xs text-muted-foreground">
                    {item.evidence_ids.map((id) => `[E${id}]`).join(" ")}
                  </span>
                </li>
              ))}
            </ul>
          </section>
        ))}

      <section aria-labelledby="sources-heading" className="space-y-1">
        <h2 id="sources-heading" className="text-base font-medium">
          Sources
        </h2>
        {(data.sources ?? []).length === 0 ? (
          <p className="text-sm">No sources were recorded for this report.</p>
        ) : (
          <ol className="space-y-2 text-sm">
            {(data.sources ?? []).map((s) => (
              <li key={s.evidenceId} data-testid="source-item" className="break-words">
                <span className="font-medium">{`[E${s.evidenceId}]`}</span>{" "}
                <span>{s.title ?? "Untitled source"}</span>
                <span className="block text-xs text-muted-foreground">
                  {`${s.publisher ?? "Publisher not stated"} · ${s.date ?? "date not available"}`}
                </span>
                <a
                  href={/^https?:\/\//i.test(s.url) ? s.url : undefined}
                  target="_blank"
                  rel="noopener noreferrer"
                  className="block text-xs underline"
                >
                  {s.url}
                </a>
              </li>
            ))}
          </ol>
        )}
      </section>

      {data.missingDocuments.length > 0 ? (
        <section>
          <h2 className="text-base font-medium">Missing documents</h2>
          <ul className="list-disc pl-5 text-sm">
            {data.missingDocuments.map((m) => (
              <li key={m}>{m}</li>
            ))}
          </ul>
        </section>
      ) : null}
      {data.limitations.length > 0 ? (
        <section>
          <h2 className="text-base font-medium">Limitations</h2>
          <ul className="list-disc pl-5 text-sm">
            {data.limitations.map((m) => (
              <li key={m}>{m}</li>
            ))}
          </ul>
        </section>
      ) : null}
    </article>
  );
}
